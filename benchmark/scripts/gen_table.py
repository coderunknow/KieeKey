#!/usr/bin/env python3
"""
benchmark/scripts/gen_table.py — regenerate harness/viet_table.inc

Emits the Vietnamese letter decomposition table used by the benchmark
encoders:  precomposed code point -> (base letter, hat, tone).

This is the ONLY source of composition knowledge in the harness: keystroke
streams are derived from it (and from human-authored target text), never from
an engine's own rule tables — so the benchmark cannot inherit one engine's
conventions and label them "correct".

The table is built by enumerating the Vietnamese letter *space* (base a e o u y
d  ×  hat circumflex/breve/horn  ×  tone sắc/huyền/hỏi/ngã/nặng), NFC-composing
each combination and keeping the ones Unicode encodes as a single precomposed
code point. Look-alike Latin letters that Vietnamese does not use (î û ï ä å)
are therefore never included.

Regenerate with:
    python3 benchmark/scripts/gen_table.py > benchmark/harness/viet_table.inc
"""
import unicodedata

HAT_CHAR = {"circumflex": 1, "breve": 2, "horn": 3}
TONE_CHAR = {"sac": 1, "huyen": 2, "hoi": 3, "nga": 4, "nang": 5}
COMBINING = {
    1: "\u0302",   # circumflex
    2: "\u0306",   # breve
    3: "\u031B",   # horn
}
TONES = {
    1: "\u0301",   # acute
    2: "\u0300",   # grave
    3: "\u0309",   # hook above
    4: "\u0303",   # tilde
    5: "\u0323",   # dot below
}
# Which hats each base letter may carry (the Vietnamese orthography rules the
# engines are all supposed to implement).
HATS_OK = {"a": (1, 2), "e": (1,), "o": (1, 3), "u": (3,), "i": (), "y": (), "d": ()}

rows = set()
for base in "aeoiuyd":
    for hat in (0,) + HATS_OK[base]:
        # Only vowels carry tones in Vietnamese; d never takes a hat or a tone
        # (the tone on "đó" belongs to the vowel), so a plain "d + tone" letter
        # such as U+1E0D is NOT part of the Vietnamese alphabet and must not
        # appear in the table.
        tones = (0,) if base == "d" else (0,) + tuple(TONES)
        for tone in tones:
            for b in (base, base.upper()):
                seq = b + (COMBINING[hat] if hat else "") + (TONES[tone] if tone else "")
                nfc = unicodedata.normalize("NFC", seq)
                if len(nfc) == 1:
                    rows.add((ord(nfc), b, hat, tone))

# d-bar: đ / Đ are not hat+tone compositions, they are their own letters.
for b, d in (("d", "\u0111"), ("D", "\u0110")):
    rows.add((ord(d), b, 0, 0))

entries = sorted(rows)
out = []
out.append("// GENERATED by benchmark/scripts/gen_table.py — do not edit by hand.")
out.append("// Vietnamese letter table: precomposed code point -> (base, hat, tone).")
out.append("//   hat : 0 none | 1 circumflex (â ê ô) | 2 breve (ă) | 3 horn (ơ ư)")
out.append("//   tone: 0 none | 1 sắc | 2 huyền | 3 hỏi | 4 ngã | 5 nặng")
out.append("// Entries are sorted by code point (binary-searchable).")
out.append("#ifndef BENCH_VIET_TABLE_INC")
out.append("#define BENCH_VIET_TABLE_INC")
out.append("namespace viet {")
out.append("struct RawLetter { unsigned cp; char base; unsigned char hat; unsigned char tone; };")
out.append("inline constexpr RawLetter kVietTable[] = {")
for cp, base, hat, tone in entries:
    out.append("    {0x%04X, '%s', %d, %d}," % (cp, base, hat, tone))
out.append("};")
out.append("inline constexpr unsigned kVietTableCount =")
out.append("    static_cast<unsigned>(sizeof(kVietTable) / sizeof(kVietTable[0]));")
out.append("} // namespace viet")
out.append("#endif")
print("\n".join(out))
