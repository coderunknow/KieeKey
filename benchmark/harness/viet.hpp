// Composition knowledge for the benchmark: the Vietnamese letter table, the
// keystroke encoders (Telex / VNI) and the output analyser.
//
// WHY THIS FILE EXISTS
//   A typing benchmark is only fair if the *input* is produced independently of
//   every engine under test. Encoders here are derived solely from
//   viet_table.inc (generated by scripts/gen_table.py from Unicode data) and
//   from the human-authored target text — never from an engine's own rule
//   tables. Whatever an engine outputs is then compared with the target text.
//
// Stream event language (shared with the repo's earlier campaigns, so old and
// new runs stay comparable — see imebench_kit/harness for the original):
//   'a'..'z'      plain key
//   '^' + letter  shifted letter (Shift+A)
//   '~' + char    shifted symbol (Shift+? -> '/')
//   ' '           space
//   '#'           backspace
//   '%'           word break (Enter)
//============================================================================
