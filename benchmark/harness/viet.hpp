//============================================================================
// Table access
//============================================================================
struct Letter {
    char32_t cp = 0;
    char base = 0;         // a e i o u y d (case preserved)
    uint8_t hat = 0;       // 0 none | 1 circumflex | 2 breve | 3 horn
    uint8_t tone = 0;      // 0 none | 1 sac | 2 huyen | 3 hoi | 4 nga | 5 nang
    bool upper = false;
    bool viet = false;     // cp is part of the Vietnamese alphabet
};

// Binary search in the generated table. Returns false for anything that is not
// a Vietnamese letter (ASCII consonants, digits, punctuation, non-Vietnamese
// accented Latin).
inline bool lookup(unsigned cp, Letter& out) {
    const RawLetter* lo = kVietTable;
    const RawLetter* hi = lo + kVietTableCount;
    while (lo < hi) {
        const RawLetter* mid = lo + (hi - lo) / 2;
        if (mid->cp < cp) { lo = mid + 1; }
        else if (cp < mid->cp) { hi = mid; }
        else {
            out.cp = static_cast<char32_t>(mid->cp);
            out.base = mid->base;
            out.hat = mid->hat;
            out.tone = mid->tone;
            out.upper = (mid->base >= 'A' && mid->base <= 'Z');
            out.viet = true;
            return true;
        }
    }
    out = Letter{};
    return false;
}

inline bool isVietLetter(char32_t cp) { Letter l; return lookup(static_cast<unsigned>(cp), l); }

// Convenience: Letter by value; .viet tells whether cp is a Vietnamese letter.
inline Letter letterOf(char32_t cp) {
    Letter l;
    lookup(static_cast<unsigned>(cp), l);
    return l;
}

//============================================================================
// UTF-8 <-> code points
//============================================================================
inline std::u32string utf8To32(const std::string& s) {
    std::u32string out;
    out.reserve(s.size());
    for (std::size_t i = 0; i < s.size();) {
        const unsigned char c = static_cast<unsigned char>(s[i]);
        char32_t cp = 0;
        int extra = 0;
        if (c < 0x80) { cp = c; }
        else if ((c >> 5) == 0x6) { cp = c & 0x1F; extra = 1; }
        else if ((c >> 4) == 0xE) { cp = c & 0x0F; extra = 2; }
        else if ((c >> 3) == 0x1E) { cp = c & 0x07; extra = 3; }
        else { cp = 0xFFFD; }                       // keep going, never crash
        ++i;
        for (int k = 0; k < extra && i < s.size(); ++k, ++i) {
            cp = (cp << 6) | (static_cast<unsigned char>(s[i]) & 0x3F);
        }
        out += cp;
    }
    return out;
}

// UTF-8 byte range -> wchar_t string of code points (UniKey emits UTF-8).
inline std::wstring utf8BytesToW(const unsigned char* p, std::size_t n) {
    std::wstring out;
    out.reserve(n);
    for (std::size_t i = 0; i < n;) {
        const unsigned char c = p[i];
        char32_t cp = 0;
        int extra = 0;
        if (c < 0x80) { cp = c; }
        else if ((c >> 5) == 0x6) { cp = c & 0x1F; extra = 1; }
        else if ((c >> 4) == 0xE) { cp = c & 0x0F; extra = 2; }
        else if ((c >> 3) == 0x1E) { cp = c & 0x07; extra = 3; }
        else { cp = U'?'; }
        ++i;
        for (int k = 0; k < extra && i < n; ++k, ++i) {
            cp = (cp << 6) | (static_cast<unsigned char>(p[i]) & 0x3F);
        }
        out += static_cast<wchar_t>(cp);
    }
    return out;
}

inline std::string utf32To8(const std::u32string& s) {
    std::string out;
    out.reserve(s.size());
    for (char32_t cp : s) {
        if (cp < 0x80) out += static_cast<char>(cp);
        else if (cp < 0x800) {
            out += static_cast<char>(0xC0 | (cp >> 6));
            out += static_cast<char>(0x80 | (cp & 0x3F));
        } else if (cp < 0x10000) {
            out += static_cast<char>(0xE0 | (cp >> 12));
            out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
            out += static_cast<char>(0x80 | (cp & 0x3F));
        } else {
            out += static_cast<char>(0xF0 | (cp >> 18));
            out += static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
            out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
            out += static_cast<char>(0x80 | (cp & 0x3F));
        }
    }
    return out;
}

inline std::string utf16To8(const std::wstring& w) {
    std::u32string s;
    for (std::size_t i = 0; i < w.size(); ++i) {
        const char32_t u = static_cast<char32_t>(static_cast<wchar_t>(w[i]));
        if constexpr (sizeof(wchar_t) == 2) {
            if (u >= 0xD800 && u < 0xDC00 && i + 1 < w.size()) {
                const char32_t l = static_cast<char32_t>(static_cast<wchar_t>(w[i + 1]));
                if (l >= 0xDC00 && l < 0xE000) {
                    s += 0x10000 + ((u - 0xD800) << 10) + (l - 0xDC00);
                    ++i;
                    continue;
                }
            }
        }
        s += u;
    }
    return utf32To8(s);
}

//============================================================================
// Keystroke encoding
//============================================================================
// Tone key placement: at the end of the word (how most Telex users type) or
// immediately after the vowel that carries it (exercises the engines'
// free-mark / spell-check rules).
enum class TonePos : uint8_t { EndOfWord, AfterVowel };

struct EncodeCfg {
    enum class Method : uint8_t { Telex, Vni } method = Method::Telex;
    TonePos tonePos = TonePos::EndOfWord;
};

class Encoder {
public:
    explicit Encoder(EncodeCfg cfg) : cfg_(cfg) {}

    // intended UTF-8 text -> stream language. Returns false when the text
    // contains a character outside the benchmark's keyboard model (the caller
    // drops such a corpus line rather than feeding a wrong key).
    bool encode(const std::string& intended, std::string& streamOut) const {
        std::string s;
        const std::u32string t = utf8To32(intended);
        std::u32string word;                     // pending Vietnamese word
        std::vector<int> toneAt;                 // index in word of each tone key
        for (std::size_t i = 0; i < t.size(); ++i) {
            const char32_t cp = t[i];
            const Letter L = letterOf(cp);
            const bool asciiLetter = (cp >= U'a' && cp <= U'z') || (cp >= U'A' && cp <= U'Z');
            if (asciiLetter || L.viet) {
                // A word run is every LETTER of the word, plain ASCII or
                // Vietnamese: a user types the whole word before a word-end
                // tone key, so hats and tones must bind across consonants
                // rather than stopping at them.
                word.push_back(cp);
                continue;
            }
            // A "word" = run of letters; commit it when anything else follows
            // (space, digit, punctuation, end of text).
            if (!word.empty()) {
                if (!emitWord(word, s)) { return false; }
                word.clear();
            }
            if (L.viet) {                     // bare Vietnamese letter
                word.push_back(cp);
                continue;
            }
            if (cp == U' ') { s += ' '; continue; }   // run already committed
            if (cp >= U'a' && cp <= U'z') { s += static_cast<char>(cp); continue; }
            if (cp >= U'A' && cp <= U'Z') { s += '^'; s += static_cast<char>(cp - U'A' + U'a'); continue; }
            if (cp >= U'0' && cp <= U'9') { s += static_cast<char>(cp); continue; }
            switch (cp) {
                case U',': case U'.': case U';': case U':': case U'/':
                case U'-': case U'=': case U'[': case U']': case U'\'':
                    s += static_cast<char>(cp); continue;
                case U'?': case U'!': case U'(': case U')': case U'"':
                    s += '~'; s += static_cast<char>(cp); continue;
                default: return false;            // not modelled (emoji, …)
            }
        }
        if (!word.empty() && !emitWord(word, s)) { return false; }
        streamOut = s;
        return !streamOut.empty();
    }

private:
    // Encodes one run of Vietnamese letters (with marks) into keystrokes.
    bool emitWord(const std::u32string& w, std::string& s) const {
        char pendingTone = 0;                    // for TonePos::EndOfWord
        std::u32string tmp;
        tmp.reserve(w.size());
        (void)tmp;
        for (char32_t cp : w) {
            const Letter L = letterOf(cp);
            if (!L.viet) {
                // plain ASCII letter inside the word: typed as-is
                const bool up = (cp >= U'A' && cp <= U'Z');
                if (cp >= U'a' && cp <= U'z') { s += static_cast<char>(cp); continue; }
                if (up) { s += '^'; s += static_cast<char>(cp + 32); continue; }
                return false;
            }
            const bool upper = (cp >= U'A' && cp <= U'Z') || (L.upper);
            const char base = static_cast<char>(L.base);            // keeps case
            const char lower = static_cast<char>(base >= 'A' && base <= 'Z' ? base + 32 : base);
            const bool dBar = (cp == U'\u0111' || cp == U'\u0110');  // đ AND Đ (both need the doubled d)
            if (cfg_.method == EncodeCfg::Method::Telex) {
                if (lower == 'd' && dBar) {                           // d-bar: "dd"
                    if (upper) { s += '^'; s += 'd'; } else { s += 'd'; }
                    s += 'd';
                } else if (upper) {
                    s += '^'; s += lower;
                } else {
                    s += lower;
                }
                switch (L.hat) {
                    case 1: s += lower; break;                       // aa ee oo
                    case 2: s += 'w'; break;                         // aw -> ă
                    case 3: s += 'w'; break;                         // ow uw -> ơ ư
                    default: break;
                }
                char tk = 0;
                switch (L.tone) { case 1: tk = 's'; break; case 2: tk = 'f'; break;
                    case 3: tk = 'r'; break; case 4: tk = 'x'; break;
                    case 5: tk = 'j'; break; default: break; }
                if (tk) {
                    if (cfg_.tonePos == TonePos::AfterVowel) { s += tk; }
                    else if (pendingTone) { return false; }         // two tones in one word: skip
                    else { pendingTone = tk; }
                }
            } else {                                                 // VNI
                if (lower == 'd' && dBar) {
                    if (upper) { s += '^'; s += 'd'; } else { s += 'd'; }
                    s += '9';
                } else if (upper) {
                    s += '^'; s += lower;
                } else {
                    s += lower;
                }
                char hk = 0;
                switch (L.hat) { case 1: hk = '6'; break; case 2: hk = '8'; break;
                    case 3: hk = '7'; break; default: break; }
                if (hk) { s += hk; }
                char tk = 0;
                switch (L.tone) { case 1: tk = '1'; break; case 2: tk = '2'; break;
                    case 3: tk = '3'; break; case 4: tk = '4'; break;
                    case 5: tk = '5'; break; default: break; }
                if (tk) {
                    if (cfg_.tonePos == TonePos::AfterVowel) { s += tk; }
                    else if (pendingTone) { return false; }
                    else { pendingTone = tk; }
                }
            }
        }
        if (pendingTone) { s += pendingTone; }
        return true;
    }

    EncodeCfg cfg_;
};

//============================================================================
// Output analysis — how far is the engine's text from the intended text?
//============================================================================
enum class Verdict : uint8_t {
    Exact = 0,        // byte-for-byte identical
    CaseOnly,        // only Shift/Caps-Lock casing differs
    RestoredRaw,     // engine gave up and emitted the raw letters (auto-restore)
    NoTone,          // right letters+hats, tone(s) missing
    ToneWrong,       // right letters+hats, a different tone
    TonePosition,    // same tones, placed on a different vowel
    HatWrong,        // hat missing/extra/changed
    LettersDiffer,   // letters differ (dropped/inserted/reordered)
    Count
};

inline const char* verdictName(Verdict v) {
    switch (v) {
        case Verdict::Exact: return "exact";
        case Verdict::CaseOnly: return "case_only";
        case Verdict::RestoredRaw: return "restored_raw";
        case Verdict::NoTone: return "tone_missing";
        case Verdict::ToneWrong: return "tone_wrong";
        case Verdict::TonePosition: return "tone_position";
        case Verdict::HatWrong: return "hat_wrong";
        case Verdict::LettersDiffer: return "letters_differ";
        default: return "count";
    }
}

// Decompose a token into per-character (base, hat, tone) triples.
struct Sig {
    std::string base;                 // lowercase base letters
    std::vector<uint8_t> hat;
    std::vector<uint8_t> tone;
    std::string raw;                  // plain upper/lower case text, no marks
    std::string utf8;                 // original (decomposed) text for display
};

inline Sig signature(const std::string& utf8) {
    Sig s;
    s.utf8 = utf8;
    for (char32_t cp : utf8To32(utf8)) {
        const Letter L = letterOf(cp);
        if (!L.viet) {
            // Non-Vietnamese char: keep it as its own "base" with no marks so
            // length differences still show up as letters_differ.
            s.base += static_cast<char>(cp < 0x80 ? cp : U'?');
            s.raw += static_cast<char>(cp < 0x80 ? cp : U'?');
            s.hat.push_back(0);
            s.tone.push_back(0);
            continue;
        }
        const char lower = static_cast<char>(L.base >= 'A' && L.base <= 'Z' ? L.base + 32 : L.base);
        s.base += lower;
        s.raw += L.base;
        s.hat.push_back(L.hat);
        s.tone.push_back(L.tone);
    }
    return s;
}

// Strip every mark from a string (used to recognise the "engine gave up and
// left the raw letters" outcome).
inline std::string deaccent(const std::string& utf8) {
    std::string out;
    for (char32_t cp : utf8To32(utf8)) {
        const Letter L = letterOf(cp);
        if (L.viet) { out += L.upper ? static_cast<char>(L.base) : static_cast<char>(L.base); }
        else { out += static_cast<char>(cp < 0x80 ? cp : U'?'); }
    }
    return out;
}

// `rawKeys` is the encoder's own keystroke stream for `intended` (without the
// trailing space): it lets us tell "engine reverted to the typed letters"
// (an explicit engine policy: auto-restore) apart from genuine garbling.
inline Verdict classify(const std::string& intended, const std::string& actual,
                        const std::string& rawKeys) {
    if (intended == actual) { return Verdict::Exact; }
    const Sig a = signature(intended);
    const Sig b = signature(actual);

    // Restored raw: engine output (marks stripped, case-insensitive) == the
    // letters that were typed.
    std::string typedLower;
    for (char c : rawKeys) {
        if (c == '^' || c == '~') { continue; }
        typedLower += static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    }
    std::string actualLower;
    for (char c : deaccent(actual)) {
        actualLower += static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    }
    if (!typedLower.empty() && actualLower == typedLower) { return Verdict::RestoredRaw; }

    if (a.base.size() != b.base.size()) { return Verdict::LettersDiffer; }
    bool hatsEq = true, tonesEq = true, baseEq = true;
    std::size_t toneDiff = 0, hatDiff = 0;
    for (std::size_t i = 0; i < a.base.size(); ++i) {
        if (a.base[i] != b.base[i]) { baseEq = false; }
        if (a.hat[i] != b.hat[i]) { hatsEq = false; ++hatDiff; }
        if (a.tone[i] != b.tone[i]) { tonesEq = false; ++toneDiff; }
    }
    if (!baseEq) { return Verdict::LettersDiffer; }
    if (a.raw == b.raw) { return Verdict::CaseOnly; }
    if (!hatsEq) { return Verdict::HatWrong; }
    if (tonesEq) { return Verdict::CaseOnly; }
    std::vector<uint8_t> ta = a.tone, tb = b.tone;
    std::sort(ta.begin(), ta.end());
    std::sort(tb.begin(), tb.end());
    const bool anyTone = std::any_of(a.tone.begin(), a.tone.end(),
                                     [](uint8_t v) { return v != 0; });
    if (ta == tb) { return Verdict::TonePosition; }        // same tones, other vowel
    if (anyTone && std::all_of(b.tone.begin(), b.tone.end(),
                               [](uint8_t v) { return v == 0; })) {
        return Verdict::NoTone;
    }
    (void)toneDiff; (void)hatDiff;
    return Verdict::ToneWrong;
}

// Deterministic pseudo-random keystroke stream (edit storm: words, spaces,
// backspaces) — same generator shape as the repo's earlier campaigns so the
// "fuzz" label means the same thing, but with an explicit alphabet mix.
inline std::string makeFuzz(uint64_t seed, std::size_t nKeys) {
    static const std::string alpha = "abcdefghijklmnopqrstuvwxyz";
    std::string out;
    uint64_t x = seed * 6364136223846793005ULL + 1442695040888963407ULL;
    auto rnd = [&x]() { x = x * 6364136223846793005ULL + 1442695040888963407ULL; return x; };
    while (out.size() < nKeys) {
        const std::size_t wlen = 1 + ((rnd() >> 43) % 11);
        for (std::size_t k = 0; k < wlen && out.size() < nKeys; ++k) {
            out += alpha[(rnd() >> 43) % alpha.size()];
        }
        if (out.size() >= nKeys) { break; }
        const unsigned r = static_cast<unsigned>((rnd() >> 33) % 100);
        if (r < 7) { out += '#'; }
        else if (r < 12 && out.size() >= 2) { out += "##"; }
        else { out += (r < 90) ? ' ' : (r < 95 ? ',' : '.'); }
    }
    return out;
}

